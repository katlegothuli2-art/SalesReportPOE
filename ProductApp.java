    private void productFieldActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_productFieldActionPerformed
        // TODO add your handling code here:
        
        //Declarations needed for the applicaton
        String customerName = customerNameField.getText();
        String product = productField.getSelectedItem().toString();
        double productPrice = Double.parseDouble(priceField.getText());
        
        if(productPrice<=0){
            JOptionPane.showMessageDialog(this, "Product Price must be less");
        }
            
         
        //Calculations
        //double subTotal = productPrice ;
        double vatAmount = 0.15 * productPrice;
        double commissionAmount = 0.05 * productPrice;
        double totalSaleAmount = productPrice + vatAmount + commissionAmount;
        
        
        //Displays information in a message dialog
        JOptionPane.showMessageDialog(this, 
                "Customer Name: " + customerName + "\n" +
                "Product: " + product + "\n" +
                "VAT:" + vatAmount + "\n" +
                "COMMISSION: " + commissionAmount + "\n" + 
                "TOTAL: " + totalSaleAmount) ;
        
        
    }//GEN-LAST:event_productFieldActionPerformed

